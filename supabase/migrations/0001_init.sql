-- Biniso initial schema
-- Run once in the Supabase SQL Editor (or `supabase db push` if you use the CLI).

create extension if not exists "pgcrypto";

-- Is the current request an authenticated admin?
-- Admins are marked with app_metadata.role = 'admin' on their auth user.
create or replace function public.is_admin()
returns boolean
language sql
stable
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

-- products -----------------------------------------------------------------
create table if not exists public.products (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  price       numeric(12,2) not null default 0 check (price >= 0),
  description text,
  image       text,
  category    text,
  status      text not null default 'active'
              check (status in ('active', 'inactive', 'draft')),
  featured    boolean not null default false,
  created_at  timestamptz not null default now()
);

create index if not exists products_status_idx   on public.products (status);
create index if not exists products_category_idx on public.products (category);
create index if not exists products_featured_idx on public.products (featured) where featured;

-- orders -------------------------------------------------------------------
create table if not exists public.orders (
  id              uuid primary key default gen_random_uuid(),
  customer_name   text not null,
  phone           text not null,
  email           text,
  city            text,
  address         text not null,
  notes           text,
  subtotal        numeric(12,2) not null default 0,
  delivery_method text not null default 'inside_dhaka'
                  check (delivery_method in ('inside_dhaka', 'outside_dhaka', 'pickup')),
  delivery_fee    numeric(12,2) not null default 0,
  total           numeric(12,2) not null default 0,
  status          text not null default 'pending'
                  check (status in ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')),
  created_at      timestamptz not null default now()
);

create index if not exists orders_status_idx     on public.orders (status);
create index if not exists orders_created_at_idx on public.orders (created_at desc);

-- order_items --------------------------------------------------------------
create table if not exists public.order_items (
  id         bigint generated by default as identity primary key,
  order_id   uuid not null references public.orders (id) on delete cascade,
  product_id uuid references public.products (id) on delete set null,
  quantity   integer not null default 1 check (quantity > 0),
  price      numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists order_items_order_id_idx   on public.order_items (order_id);
create index if not exists order_items_product_id_idx on public.order_items (product_id);

-- Row Level Security -------------------------------------------------------
alter table public.products    enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

-- products: everyone reads active products; admins read and write everything.
drop policy if exists "products public read" on public.products;
create policy "products public read"
  on public.products for select
  to anon, authenticated
  using (status = 'active' or public.is_admin());

drop policy if exists "products admin write" on public.products;
create policy "products admin write"
  on public.products for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- orders: admin-only. Guests create orders through the checkout server action,
-- which uses the service role key (service role bypasses RLS).
drop policy if exists "orders admin read" on public.orders;
create policy "orders admin read"
  on public.orders for select
  to authenticated
  using (public.is_admin());

drop policy if exists "orders admin update" on public.orders;
create policy "orders admin update"
  on public.orders for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "orders admin delete" on public.orders;
create policy "orders admin delete"
  on public.orders for delete
  to authenticated
  using (public.is_admin());

-- order_items: admin-only, same reasoning as orders.
drop policy if exists "order_items admin all" on public.order_items;
create policy "order_items admin all"
  on public.order_items for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

